#!/usr/bin/env node
/**
 * Scans assets/art/ and regenerates src/assets/art.generated.ts.
 * Metro only bundles static require() calls, so this turns "whatever images
 * exist right now" into a typed map. Missing slots fall back to vector art.
 *
 *   npm run art        (also runs automatically before `npm start`)
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ART_DIR = path.join(ROOT, 'assets', 'art');
const OUT = path.join(ROOT, 'src', 'assets', 'art.generated.ts');
const SLOTS = require(path.join(ROOT, 'src', 'assets', 'slots.json'));
const EXT = ['.webp', '.jpg', '.jpeg', '.png'];

const files = fs.existsSync(ART_DIR) ? fs.readdirSync(ART_DIR) : [];
const found = [];
const missing = [];

for (const slot of SLOTS.map((s) => s.slot)) {
  const file = EXT.map((e) => slot + e).find((f) => files.includes(f));
  if (file) found.push([slot, file]);
  else missing.push(slot);
}

const lines = [
  '// AUTO-GENERATED by scripts/sync-art.js — do not edit. Run `npm run art` after adding images.',
  "import type { ArtSlot } from './slots';",
  '',
  'export const ART: Partial<Record<ArtSlot, number>> = {',
  ...found.map(([slot, file]) => `  '${slot}': require('../../assets/art/${file}'),`),
  '};',
  '',
];
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));

console.log(`[art] ${found.length}/${SLOTS.length} slots filled.`);
if (missing.length) console.log(`[art] missing (vector fallback used): ${missing.join(', ')}`);
